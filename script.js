/* GME tracker — data loading strategy (per dataset):
   1) same-origin proxy  /api/*   (serve.py, live, cached 5 min)
   2) direct public endpoint      (chart only; usually blocked by CORS in browsers)
   3) data.json snapshot           (dated, generated by snapshot.py)
   4) give up -> show "unavailable" (chart: embed TradingView widget instead)
   Nothing is ever invented. */
const $ = id => document.getElementById(id);
const fmtUSD = (n, d = 2) => n == null || isNaN(n) ? '—' : '$' + n.toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
const fmtBig = n => n >= 1e12 ? (n / 1e12).toFixed(2) + 'T' : n >= 1e9 ? (n / 1e9).toFixed(2) + 'B' : n >= 1e6 ? (n / 1e6).toFixed(2) + 'M' : n?.toLocaleString('en-US');
const fmtDate = s => new Date(s + 'T12:00:00').toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });

let snapshot; // lazy-loaded data.json
async function getSnapshot() {
  if (snapshot === undefined) {
    try { const r = await fetch('data.json', { cache: 'no-store' }); snapshot = r.ok ? await r.json() : null; } catch { snapshot = null; }
  }
  return snapshot;
}
async function getJSON(url, ms = 9000) {
  const ctl = new AbortController(); const t = setTimeout(() => ctl.abort(), ms);
  try { const r = await fetch(url, { signal: ctl.signal }); if (!r.ok) throw new Error(r.status); const j = await r.json(); if (j.error) throw new Error(j.error); return j; }
  finally { clearTimeout(t); }
}
// On static hosts (GitHub Pages) there is no /api proxy, and Yahoo blocks browser CORS, so go straight to data.json.
const STATIC_HOST = /github\.io$/.test(location.hostname) || location.protocol === 'file:';
/** returns {data, mode:'live'|'snapshot', stamp} or null */
async function load(name, urls, range) {
  for (const u of STATIC_HOST ? [] : urls) { try { return { data: await getJSON(u), mode: 'live' }; } catch (e) { console.info(`[gme] ${u} failed:`, e.message || e); } }
  const s = await getSnapshot();
  if (name === 'chart' && s?.charts?.[range]) return { data: s.charts[range], mode: 'snapshot', stamp: s.generated };
  if (s && s[name] && !s[name].error) return { data: s[name], mode: 'snapshot', stamp: s.generated };
  return null;
}

/* ---------------- price + chart ---------------- */
let currentRange = '6mo';
let firstQuote = true;
async function loadChart(range) {
  currentRange = range;
  $('chartMsg').textContent = 'Loading chart…';
  const urls = [`/api/chart?range=${range}`,
    `https://query1.finance.yahoo.com/v8/finance/chart/GME?range=${range}&interval=${{ '1d': '5m', '5d': '15m', '1mo': '1d', '6mo': '1d', '1y': '1d', '5y': '1wk', max: '1mo' }[range]}`];
  let res = await load('chart', urls, range);
  if (res && res.mode === 'snapshot' && range !== '6mo' && !snapshot?.charts?.[range]) res.note = 'Only the 6M range is in the offline snapshot.';
  const result = res?.data?.chart?.result?.[0];
  if (!result) return fallbackTradingView();
  const m = result.meta, q = result.indicators.quote[0], ts = result.timestamp || [];
  const pts = ts.map((t, i) => ({ t: t * 1000, c: q.close[i] })).filter(p => p.c != null);

  if (firstQuote || res.mode === 'live') {
    const price = m.regularMarketPrice, prev = m.chartPreviousClose ?? m.previousClose;
    const dayPrev = m.regularMarketPreviousClose ?? (m.fulldayChange != null ? price - m.fulldayChange : null);
    const ref = dayPrev ?? (range === '5d' || range === '1d' ? prev : null);
    $('priceVal').textContent = fmtUSD(price);
    $('heroPrice').textContent = fmtUSD(price);
    if (ref) {
      const ch = price - ref, pct = ch / ref * 100, cls = ch >= 0 ? 'up' : 'down', s = (ch >= 0 ? '+' : '') + ch.toFixed(2) + ' (' + (ch >= 0 ? '+' : '') + pct.toFixed(2) + '%)';
      $('chg').textContent = s + ' vs prev close'; $('chg').className = 'chg ' + cls;
      $('heroChg').textContent = s; $('heroChg').className = 'ht-chg ' + cls;
    } else { $('chg').textContent = ''; $('heroChg').textContent = ''; }
    $('dayRange').textContent = m.regularMarketDayLow ? `${fmtUSD(m.regularMarketDayLow)} – ${fmtUSD(m.regularMarketDayHigh)}` : '—';
    $('wkRange').textContent = m.fiftyTwoWeekLow ? `${fmtUSD(m.fiftyTwoWeekLow)} – ${fmtUSD(m.fiftyTwoWeekHigh)}` : '—';
    $('vol').textContent = m.regularMarketVolume ? fmtBig(m.regularMarketVolume) : '—';
    $('prevClose').textContent = fmtUSD(dayPrev);
    const when = new Date(m.regularMarketTime * 1000).toLocaleString('en-US', { timeZone: 'America/New_York', month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' });
    $('priceStatus').innerHTML = (res.mode === 'live' ? '<span class="up">● Live</span>' : `<span class="down">● Snapshot ${new Date(res.stamp).toLocaleString('en-US', { timeZone: 'America/New_York', month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' })} ET</span>`) +
      ` · last trade ${when} ET · source: Yahoo Finance chart feed (may be delayed)`;
    window.__price = price; firstQuote = false; updateComputed();
  }
  drawChart(pts, range);
  $('chartMsg').textContent = res.note || '';
}

function drawChart(pts, range) {
  const svg = $('chart'), W = 1000, H = 320, pad = { t: 16, b: 28, l: 0, r: 56 };
  if (pts.length < 2) { svg.innerHTML = ''; $('chartMsg').textContent = 'Not enough data for this range.'; return; }
  const min = Math.min(...pts.map(p => p.c)), max = Math.max(...pts.map(p => p.c)), span = (max - min) || 1;
  const x = i => pad.l + i / (pts.length - 1) * (W - pad.l - pad.r);
  const y = v => pad.t + (1 - (v - min) / span) * (H - pad.t - pad.b);
  const up = pts.at(-1).c >= pts[0].c, col = up ? '#21d07a' : '#ff3b41';
  const line = pts.map((p, i) => `${i ? 'L' : 'M'}${x(i).toFixed(1)},${y(p.c).toFixed(1)}`).join('');
  let grid = '';
  for (let k = 0; k <= 4; k++) {
    const v = min + span * k / 4, yy = y(v);
    grid += `<line x1="0" x2="${W - pad.r}" y1="${yy}" y2="${yy}" stroke="#23232d" stroke-dasharray="3 5" vector-effect="non-scaling-stroke"/>` +
      `<text x="${W - pad.r + 8}" y="${yy + 4}" fill="#8a8a98" font-size="12" font-family="JetBrains Mono">${v >= 100 ? v.toFixed(0) : v.toFixed(2)}</text>`;
  }
  const opt = range === '1d' ? { hour: 'numeric', minute: '2-digit', timeZone: 'America/New_York' } : range === '5d' ? { weekday: 'short' } : (range === '5y' || range === 'max') ? { year: 'numeric' } : { month: 'short', day: 'numeric' };
  for (let k = 0; k < 5; k++) {
    const i = Math.round(k / 4 * (pts.length - 1));
    grid += `<text x="${x(i)}" y="${H - 6}" fill="#8a8a98" font-size="12" font-family="JetBrains Mono" text-anchor="${k === 0 ? 'start' : k === 4 ? 'end' : 'middle'}">${new Date(pts[i].t).toLocaleDateString('en-US', opt)}</text>`;
  }
  svg.innerHTML = `<defs><linearGradient id="fill" x1="0" x2="0" y1="0" y2="1"><stop offset="0" stop-color="${col}" stop-opacity=".35"/><stop offset="1" stop-color="${col}" stop-opacity="0"/></linearGradient></defs>
    ${grid}<path d="${line}L${x(pts.length - 1)},${H - pad.b}L${x(0)},${H - pad.b}Z" fill="url(#fill)"/>
    <path d="${line}" fill="none" stroke="${col}" stroke-width="2.2" vector-effect="non-scaling-stroke" stroke-linejoin="round"/>
    <line id="cross" y1="${pad.t}" y2="${H - pad.b}" stroke="#666" stroke-dasharray="2 3" vector-effect="non-scaling-stroke" visibility="hidden"/>
    <circle id="dot" r="4" fill="${col}" visibility="hidden"/>`;
  const wrap = $('chartWrap'), tip = $('tip');
  wrap.onmousemove = e => {
    const r = svg.getBoundingClientRect(), fx = (e.clientX - r.left) / r.width * W;
    const i = Math.max(0, Math.min(pts.length - 1, Math.round((fx - pad.l) / (W - pad.l - pad.r) * (pts.length - 1))));
    const cx = x(i), cy = y(pts[i].c);
    svg.querySelector('#cross').setAttribute('x1', cx); svg.querySelector('#cross').setAttribute('x2', cx);
    svg.querySelector('#cross').setAttribute('visibility', 'visible');
    const d = svg.querySelector('#dot'); d.setAttribute('cx', cx); d.setAttribute('cy', cy); d.setAttribute('visibility', 'visible');
    tip.hidden = false; tip.style.left = (cx / W * r.width) + 'px';
    tip.textContent = `${new Date(pts[i].t).toLocaleString('en-US', (range === '5d' || range === '1d') ? { month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' } : { month: 'short', day: 'numeric', year: 'numeric' })} · ${fmtUSD(pts[i].c)}`;
  };
  wrap.onmouseleave = () => { tip.hidden = true; svg.querySelector('#cross')?.setAttribute('visibility', 'hidden'); svg.querySelector('#dot')?.setAttribute('visibility', 'hidden'); };
}

function fallbackTradingView() {
  $('priceStatus').textContent = 'Direct quote feed unavailable (likely CORS) — showing TradingView widget.';
  document.querySelector('.ranges').style.display = 'none';
  const wrap = $('chartWrap'); wrap.innerHTML = '<div class="tv-embed" id="tv"></div>'; wrap.style.height = '420px';
  const s = document.createElement('script');
  s.src = 'https://s3.tradingview.com/external-embedding/embed-widget-advanced-chart.js'; s.async = true;
  s.innerHTML = JSON.stringify({ symbol: 'NYSE:GME', interval: 'D', theme: 'dark', style: '3', locale: 'en', autosize: true, hide_top_toolbar: false, backgroundColor: '#121218' });
  $('tv').appendChild(s);
  ['priceVal', 'heroPrice'].forEach(i => $(i).textContent = 'see chart'); $('heroChg').textContent = '';
  updateComputed();
}

/* ---------------- stats ---------------- */
let sharesData, shortData;
const na = (id, msg = 'unavailable') => { $(id).textContent = msg; $(id).classList.add('na'); };
const stampTxt = r => r.mode === 'snapshot' ? ` · snapshot ${r.stamp?.slice(0, 10)}` : ' · live';

async function loadStats() {
  const [sh, si] = await Promise.all([load('shares', ['/api/shares']), load('short', ['/api/short'])]);
  if (sh) {
    sharesData = sh.data;
    $('shares').textContent = fmtBig(sh.data.shares);
    $('sharesSrc').innerHTML = `<a href="https://www.sec.gov/Archives/edgar/data/1326380/${sh.data.accn.replace(/-/g, '')}/${sh.data.accn}-index.htm" target="_blank" rel="noopener">SEC ${sh.data.form}</a> cover page, as of ${fmtDate(sh.data.asOf)}${stampTxt(sh)}`;
  } else na('shares');
  if (si && si.data.rows?.length) {
    shortData = si.data; const last = si.data.rows.at(-1);
    $('si').textContent = fmtBig(last.short);
    const d = last.short - last.prev;
    $('siSrc').innerHTML = `<a href="https://www.finra.org/finra-data/browse-catalog/equity-short-interest/data" target="_blank" rel="noopener">FINRA</a> settlement ${fmtDate(last.date)} · ${d >= 0 ? '+' : '−'}${fmtBig(Math.abs(d))} vs prior${stampTxt(si)}`;
    $('dtc').textContent = last.dtc?.toFixed(2) + ' days';
    $('dtcSrc').innerHTML = `FINRA · avg daily vol ${fmtBig(last.adv)} · ${fmtDate(last.date)}`;
    const mx = Math.max(...si.data.rows.map(r => r.short));
    $('siBars').innerHTML = si.data.rows.map(r => `<div style="height:${(r.short / mx * 100).toFixed(1)}%" title="${fmtDate(r.date)}: ${fmtBig(r.short)}"><span>${new Date(r.date + 'T12:00').toLocaleDateString('en-US', { month: 'numeric', day: 'numeric' })}</span></div>`).join('');
  } else { na('si'); na('dtc'); $('siBars').innerHTML = '<span class="muted small">unavailable</span>'; }
  updateComputed();
}

function updateComputed() {
  if (sharesData && window.__price) {
    $('mcap').textContent = '$' + fmtBig(window.__price * sharesData.shares); $('mcap').classList.remove('na');
    $('mcapSrc').textContent = `${fmtUSD(window.__price)} × ${fmtBig(sharesData.shares)} SEC-reported shares (${fmtDate(sharesData.asOf)})`;
  } else if (sharesData === undefined && !window.__price) { /* still loading */ } else na('mcap', 'unavailable');
  if (sharesData && shortData?.rows?.length) {
    $('siPct').textContent = (shortData.rows.at(-1).short / sharesData.shares * 100).toFixed(2) + '%';
  } else if (sharesData !== undefined || shortData !== undefined) na('siPct', 'unavailable');
}

/* ---------------- filings ---------------- */
async function loadFilings() {
  const r = await load('filings', ['/api/filings']);
  if (!r) { $('filingsStatus').innerHTML = 'unavailable — <a href="https://www.sec.gov/cgi-bin/browse-edgar?action=getcompany&CIK=0001326380" target="_blank" rel="noopener">browse on EDGAR</a>'; return; }
  const key = /^(10-K|10-Q|8-K|DEF 14A|SC 13D|SCHEDULE 13D)/;
  $('filingsStatus').textContent = 'SEC EDGAR' + stampTxt(r);
  const desc = f => ({ '4': 'Insider transaction', '144': 'Proposed sale of securities' }[f.form] || f.desc || f.form);
  $('filings').innerHTML = r.data.filings.slice(0, 12).map(f =>
    `<li><span class="form ${key.test(f.form) ? 'key' : ''}">${f.form}</span><span class="fdate">${f.date}</span><a href="${f.url}" target="_blank" rel="noopener">${desc(f)}</a></li>`).join('');
}

